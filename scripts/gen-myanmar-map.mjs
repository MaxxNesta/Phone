// Myanmar's states and regions as SVG paths, for the sales-by-region map (2026-11-27).
//
//   node scripts/gen-myanmar-map.mjs <mmr.geojson>   → writes lib/myanmar-map.ts
//
// Source: Natural Earth 10m admin-1 states and provinces (public domain),
// https://github.com/nvkelso/natural-earth-vector — geojson/ne_10m_admin_1_states_provinces.geojson,
// filtered to adm0_a3 = MMR. Run once; the page draws the result as plain SVG, no map library,
// nothing fetched by the browser. Natural Earth keeps Nay Pyi Taw inside Mandalay, so the
// union territory is a point (its city) drawn over it.
import { readFileSync, writeFileSync } from "node:fs";

const src = JSON.parse(readFileSync(process.argv[2], "utf8"));
const H = 560;                     // drawing height; width follows the country's shape
const TOL = 0.9;                   // simplification, in drawing units
const MIN_AREA = 3;                // islands smaller than this (square units) are dropped
const NAME = { "Rakhine State": "Rakhine", "Chin State": "Chin", "Kachin State": "Kachin", "Shan State": "Shan",
  "Kayah State": "Kayah", "Kayin State": "Kayin", "Mon State": "Mon" };

const rings = (g) => (g.type === "Polygon" ? [g.coordinates] : g.coordinates);
const all = src.features.flatMap((f) => rings(f.geometry).flat(3));
const lons = all.filter((_, i) => i % 2 === 0), lats = all.filter((_, i) => i % 2 === 1);
const [minLon, maxLon, minLat, maxLat] = [Math.min(...lons), Math.max(...lons), Math.min(...lats), Math.max(...lats)];
const k = Math.cos(((minLat + maxLat) / 2) * Math.PI / 180);
const scale = H / (maxLat - minLat);
const W = Math.ceil((maxLon - minLon) * k * scale);
const proj = ([lon, lat]) => [(lon - minLon) * k * scale, (maxLat - lat) * scale];

// A ring starts and ends on one point, which gives Douglas–Peucker a line of no
// length to measure from: split it at the point farthest from the start.
function simplify(ring) {
  if (ring.length < 4) return ring;
  let m = 1, far = 0;
  ring.forEach(([x, y], i) => { const d = Math.hypot(x - ring[0][0], y - ring[0][1]); if (d > far) { far = d; m = i; } });
  return [...dp(ring.slice(0, m + 1)).slice(0, -1), ...dp(ring.slice(m))];
}
// Douglas–Peucker on an open line.
function dp(pts) {
  if (pts.length < 4) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop(); let far = 0, at = -1;
    const [x1, y1] = pts[a], [x2, y2] = pts[b], dx = x2 - x1, dy = y2 - y1, len = Math.hypot(dx, dy) || 1;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + x2 * y1 - y2 * x1) / len;
      if (d > far) { far = d; at = i; }
    }
    if (far > TOL) { keep[at] = 1; stack.push([a, at], [at, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}
const area = (p) => Math.abs(p.reduce((s, [x, y], i) => { const [x2, y2] = p[(i + 1) % p.length]; return s + x * y2 - x2 * y; }, 0)) / 2;
const r1 = (n) => Math.round(n * 10) / 10;

const regions = src.features.map((f) => {
  const name = NAME[f.properties.name_en] ?? f.properties.name_en;
  const parts = rings(f.geometry).map((poly) => poly.map((ring) => simplify(ring.map(proj))))
    .filter((poly) => area(poly[0]) >= MIN_AREA);
  const d = parts.map((poly) => poly.filter((r) => r.length >= 3)
    .map((r) => "M" + r.map(([x, y]) => `${r1(x)},${r1(y)}`).join("L") + "Z").join("")).join("");
  // Label at the largest part's area-weighted centre.
  const main = parts.map((p) => p[0]).sort((a, b) => area(b) - area(a))[0];
  if (!main) throw new Error(`${name}: nothing left after simplifying (${rings(f.geometry).length} parts)`);
  let cx = 0, cy = 0, A = 0;
  main.forEach(([x, y], i) => { const [x2, y2] = main[(i + 1) % main.length]; const c = x * y2 - x2 * y; A += c; cx += (x + x2) * c; cy += (y + y2) * c; });
  return { name, d, cx: r1(cx / (3 * A)), cy: r1(cy / (3 * A)) };
}).sort((a, b) => a.name.localeCompare(b.name));

const [nx, ny] = proj([96.1297, 19.7633]);   // Nay Pyi Taw
const out = `// Generated by scripts/gen-myanmar-map.mjs from Natural Earth (public domain). Do not edit by hand.
export const MM_VIEW = { w: ${W}, h: ${H} } as const;
export const MM_REGIONS: { name: string; d: string; cx: number; cy: number }[] = ${JSON.stringify(regions)};
/** Natural Earth keeps the union territory inside Mandalay: drawn as its city. */
export const MM_NAY_PYI_TAW = { name: "Nay Pyi Taw", x: ${r1(nx)}, y: ${r1(ny)} } as const;
`;
writeFileSync(new URL("../lib/myanmar-map.ts", import.meta.url), out);
console.log(`lib/myanmar-map.ts: ${regions.length} regions, ${W}×${H}, ${(out.length / 1024).toFixed(1)} KB`);
